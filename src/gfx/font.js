const CHARS = Object.keys(GLYPHS);
const INDEX = new Map(CHARS.map((c, i) => [c, i]));

let atlas = null; // white glyph atlas, one row of 8x8 cells
const tinted = new Map(); // color string -> tinted atlas canvas

function buildAtlas() {
  const c = document.createElement('canvas');
  c.width = CHARS.length * GLYPH_W;
  c.height = GLYPH_H;
  const ctx = c.getContext('2d');
  ctx.fillStyle = '#ffffff';
  CHARS.forEach((ch, i) => {
    const g = GLYPHS[ch];
    if (g.length !== 7 || g.some((r) => r.length !== 7)) {
      throw new Error(`Font glyph "${ch}" must be 7x7`);
    }
    for (let y = 0; y < 7; y++) {
      for (let x = 0; x < 7; x++) {
        if (g[y][x] === '#') ctx.fillRect(i * GLYPH_W + x, y, 1, 1);
      }
    }
  });
  return c;
}

function getAtlas(color) {
  if (!atlas) atlas = buildAtlas();
  let t = tinted.get(color);
  if (!t) {
    t = document.createElement('canvas');
    t.width = atlas.width;
    t.height = atlas.height;
    const ctx = t.getContext('2d');
    ctx.drawImage(atlas, 0, 0);
    ctx.globalCompositeOperation = 'source-in';
    ctx.fillStyle = color;
    ctx.fillRect(0, 0, t.width, t.height);
    tinted.set(color, t);
  }
  return t;
}

export function textWidth(text, scale = 1) {
  return String(text).length * GLYPH_W * scale;
}

export function drawText(ctx, text, x, y, color, { align = 'left', scale = 1 } = {}) {
  const str = String(text).toUpperCase();
  if (!str.length) return;
  const img = getAtlas(color);
  const w = textWidth(str, scale);
  let x0 = x;
  if (align === 'center') x0 = x - w / 2;
  else if (align === 'right') x0 = x - w;
  const size = GLYPH_W * scale;
  ctx.imageSmoothingEnabled = false;
  for (let i = 0; i < str.length; i++) {
    const idx = INDEX.get(str[i]);
    if (idx === undefined || str[i] === ' ') continue; // unknown / space -> blank
    ctx.drawImage(img, idx * GLYPH_W, 0, GLYPH_W, GLYPH_H, x0 + i * size, y, size, GLYPH_H * scale);
  }
}
